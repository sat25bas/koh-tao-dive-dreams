const fs = require('fs');
const path = require('path');

const distDir = path.join(__dirname, '..', 'dist');
const htaccessPath = path.join(distDir, '.htaccess');

if (!fs.existsSync(distDir)) {
  console.error('[write-static-htaccess] dist/ not found. Run build first.');
  process.exit(1);
}

const htaccess = `# Generated by scripts/write-static-htaccess.cjs
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  Options +FollowSymLinks -MultiViews

  # Keep API paths untouched (served externally via VITE_API_BASE_URL)
  RewriteRule ^api/ - [L]

  # Serve real files/folders as-is
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]

  # SPA fallback
  RewriteRule . index.html [L]
</IfModule>
`;

fs.writeFileSync(htaccessPath, htaccess, 'utf8');
console.log('[write-static-htaccess] Wrote dist/.htaccess');
